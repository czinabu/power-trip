import { chromium } from 'playwright';
import { pathToFileURL } from 'url';
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 960, height: 540 } });
page.on('pageerror', e => console.log('ERR', e.message));
await page.addInitScript(() => { localStorage.setItem('jpt_quality', 'low'); localStorage.setItem('sw_fullscreen', '0'); localStorage.setItem('sw_asktrain', '1'); Element.prototype.requestPointerLock = function(){ return Promise.reject(new DOMException('x','NotSupportedError')); }; });
const url = pathToFileURL('/home/user/power-trip/dist/index.html').href;
await page.goto(url); await page.waitForTimeout(4000);
const HERO = process.argv[2] || 'jedi';
const st = (l) => page.evaluate((l) => { const d = JSON.parse(localStorage.getItem('sw_save_auto') || 'null'); return l + ' ' + JSON.stringify({ mode: GAME.G.mode, ch: GAME.G.chapter, mission: GAME.G.mission && GAME.G.missionId, auto: d && [d.run && d.run.chapter, d.run && d.run.chapterId, d.where, d.modeSel], rr: GAME.G.resumeRun && [GAME.G.resumeRun.chapter, GAME.G.resumeRun.chapterId], go: document.getElementById('goText').textContent, ms: GAME.G.modeSel }); }, l);
const home = async () => { await page.evaluate(() => { document.getElementById('overlay').style.display = 'flex'; GAME.G.paused = true; GAME.setOverlayState('pause'); }); await page.click('#homeBtn'); await page.click('#homeYes'); await page.waitForTimeout(1000); };
await page.$eval('#hero-' + HERO, el => el.click()); await page.$eval('#mode-campaign', el => el.click()); await page.$eval('#goText', el => el.click());
await page.waitForTimeout(5000);
await page.evaluate(() => GAME.startChapter(5)); await page.waitForTimeout(3000);
console.log(await st('at ch5'));
// a lone mission next
await home();
console.log(await st('home'));
await page.evaluate(() => { localStorage.setItem('sw_mission_pursuit_' + GAME.G.hero, '1'); });
await page.$eval('#mode-mission', el => el.click()); await page.evaluate(() => document.getElementById('msn-pursuit').click()); await page.$eval('#goText', el => el.click());
await page.waitForTimeout(4000); await page.evaluate(() => { const b = document.querySelector('#forms [data-go]'); if (b) b.click(); }); await page.waitForTimeout(3000);
await page.evaluate(() => { GAME.spawnChampion(); }); await page.waitForTimeout(1500);
await page.evaluate(() => { const e = GAME.enemies.find(e => e.warbringer && !e.dead); if (e) GAME.damageEnemy(e, 1e6, null, 0); }); await page.waitForTimeout(3500);
console.log(await st('mission boss'));
await home();
console.log(await st('home2'));
await page.$eval('#campLoadBtn', el => el.click()); await page.click('[data-act="load"][data-i="auto"]'); await page.waitForTimeout(800);
console.log(await st('loaded'));
await page.goto(url); await page.waitForTimeout(4000);
await page.$eval('#mode-campaign', el => el.click()); await page.waitForTimeout(500);
console.log(await st('relaunch'));
await browser.close();
